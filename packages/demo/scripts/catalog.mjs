// Builds src/catalog.ts from the API's seed CSV, so demo builds show the same store as a freshly
// seeded API. Runs before every build, so the demo can't drift from the seed.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const csv = readFileSync(join(here, "../../../apps/api/src/smartcart/data/products.csv"), "utf8").trim().split("\n");
const header = csv[0].split(",");
const sections = JSON.parse(readFileSync(join(here, "../../../apps/api/src/smartcart/data/sections.json"), "utf8"));
const sectionOf = new Map(sections.flatMap((s) => s.categories.map((c) => [c, s])));
const categoryId = (section, name) => `${section.id}/${name.toLowerCase().replaceAll(" ", "-")}`;
const products = csv.slice(1).map((line, i) => {
  const r = Object.fromEntries(line.split(",").map((v, j) => [header[j], v]));
  return {
    productId: `demo-${i + 1}`,
    barcode: r.barcode,
    name: r.name,
    brand: r.brand || null,
    category: r.category,
    categoryId: categoryId(sectionOf.get(r.category), r.category),
    section: sectionOf.get(r.category).name,
    foodType: r.food_type || null,
    gstRateBp: Number(r.gst_rate_bp),
    weightG: r.weight_g ? Number(r.weight_g) : null,
    pricePaise: Number(r.price_paise),
    mrpPaise: Number(r.mrp_paise),
    dietTags: (r.diet || "").split(";").filter(Boolean),
    onHand: Number(r.on_hand),
    lowStockThreshold: Number(r.low_stock_threshold),
    aisle: r.aisle || null,
    shelf: r.shelf || null,
  };
});
const out = `// Generated by scripts/catalog.mjs from apps/api/src/smartcart/data/products.csv. Do not edit.
import type { DemoProduct } from "./types.js";

export const catalog: DemoProduct[] = ${JSON.stringify(products, null, 0).replace(/\},\{/g, "},\n  {")};
`;
writeFileSync(join(here, "../src/catalog.ts"), out);
const sectionsOut = `// Generated by scripts/catalog.mjs from apps/api/src/smartcart/data/sections.json. Do not edit.
export const sections: { id: string; name: string; icon: string; categories: { id: string; name: string }[] }[] = ${JSON.stringify(
  sections.map((s) => ({ ...s, categories: s.categories.map((c) => ({ id: categoryId(s, c), name: c })) })),
)};
`;
writeFileSync(join(here, "../src/sections.ts"), sectionsOut);
// The seed's demo offers (data/offers.csv), by product, so both demos open with the same deals.
const offerCsv = readFileSync(join(here, "../../../apps/api/src/smartcart/data/offers.csv"), "utf8").trim().split("\n");
const offerHeader = offerCsv[0].split(",");
const offers = offerCsv.slice(1).map((line) => {
  const r = Object.fromEntries(line.split(",").map((v, j) => [offerHeader[j], v]));
  const product = products.find((p) => p.barcode === r.barcode);
  if (!product) throw new Error(`offers.csv: no product with barcode ${r.barcode}`);
  return { productId: product.productId, title: r.title, offerPricePaise: Number(r.offer_price_paise), days: Number(r.days) };
});
writeFileSync(
  join(here, "../src/seed-offers.ts"),
  `// Generated by scripts/catalog.mjs from apps/api/src/smartcart/data/offers.csv. Do not edit.
export const seedOffers: { productId: string; title: string; offerPricePaise: number; days: number }[] = ${JSON.stringify(offers)};
`,
);
console.log(`Wrote ${products.length} demo products and ${offers.length} offers`);
